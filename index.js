const { Client, LocalAuth } = require('whatsapp-web.js');
const qrcode = require('qrcode-terminal');
const Groq = require('groq-sdk');

// ---------- Groq AI Setup ----------
const groq = new Groq({
    // මෙතන 'gsk_...' කියන තැනට ඔයාගේ නියම API Key එක දාන්න
    apiKey: process.env.GROQ_API_KEY, 
});

// Groq එකේ සහාය දක්වන නිවැරදි මාදිලියක් මෙලෙස යෙදුවෙමි
const GROQ_MODEL = 'qwen/qwen3.8-27b';

const SYSTEM_PROMPT = "You are a highly intelligent, friendly, and witty WhatsApp assistant for UL CREATIVE STUDIO in Sri Lanka. You MUST understand Singlish (Sinhala written in English letters) perfectly. Always reply in very natural, friendly Sinhala or Singlish based on how the user talks. Do not act like a robotic AI. Keep answers short, sweet, and helpful.";

async function getAIReply(userText) {
    try {
        const completion = await groq.chat.completions.create({
            model: GROQ_MODEL,
            messages: [
                { role: 'system', content: SYSTEM_PROMPT },
                { role: 'user', content: userText },
            ],
            max_tokens: 1024,
            temperature: 0.7,
        });
        return completion.choices[0]?.message?.content?.trim() || 'සමාවන්න, පිළිතුරක් ලැබුණේ නැත.';
    } catch (err) {
        console.error('[Groq API Error]:', err.message);
        return 'AI එකේ දෝෂයක් වුණා. පසුව උත්සාහ කරන්න.';
    }
}

// ---------- WhatsApp Connection ----------
const client = new Client({
    puppeteer: {
        args: ['--no-sandbox', '--disable-setuid-sandbox']
    }
});

client.on('qr', (qr) => {
    qrcode.generate(qr, { small: true }); 
});

client.on('ready', () => {
    console.log('✅ WhatsApp bot ready! Groq model:', GROQ_MODEL);
});

client.on('message', async (msg) => {
    // තමන්ගේම messages සහ status මගහැරීම
    if (msg.from.endsWith('@status.broadcast') || msg.fromMe) return;

    // --- 1. Sticker Maker Feature ---
    if (msg.hasMedia) {
        try {
            const media = await msg.downloadMedia();
            
            if (media && media.mimetype.includes("image")) {
                console.log('🖼️ පින්තූරයක් ලැබුණා, ස්ටිකර් එකක් සාදමින් පවතී...');
                await msg.reply(media, undefined, { 
                    sendMediaAsSticker: true,
                    stickerName: 'Custom Sticker',
                    stickerAuthor: 'UL CREATIVE STUDIO'
                });
                return; // පින්තූරයක් ආවම මෙතනින් නවත්වනවා
            }
        } catch (err) {
            console.error('මාධ්‍ය බාගත කිරීමේ දෝෂයක්:', err.message);
            await msg.reply('සමාවන්න, මේ පින්තූරය ස්ටිකර් එකක් කරන්න බැරි වුණා. 😢');
            return;
        }
    }

    const body = msg.body.trim();
    if (!body) return;

    // --- 2. Image Generation Feature (!image) ---
    if (body.startsWith('!image ')) {
        const prompt = body.substring(7).trim();
        
        if (!prompt) {
            return msg.reply('කරුණාකර පින්තූරයේ විස්තරයක් දෙන්න. \nඋදාහරණ: *!image a red racing car*');
        }

        await msg.reply('🎨 ඔයාගේ පින්තූරය නිර්මාණය කරමින් පවතී. තත්පර කිහිපයක් රැඳී සිටින්න...');

        try {
            const { MessageMedia } = require('whatsapp-web.js');
            const imageUrl = `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}`;
            
            const media = await MessageMedia.fromUrl(imageUrl, { unsafeMime: true });
            
            await msg.reply(media, undefined, { 
                caption: `🎨 *${prompt}*\n\n🌟 Generated by UL CREATIVE STUDIO` 
            });
        } catch (error) {
            console.log('Image Error:', error);
            await msg.reply('සමාවන්න! පින්තූරය නිර්මාණය කිරීමේදී කුඩා දෝෂයක් ඇති විය. 😢');
        }
        return; // මෙතනින් නවත්වනවා
    }
    
    

    // --- 4. සාමාන්‍ය AI Message (Groq) කොටස ---
    console.log('📩 Message:', body);
    const reply = await getAIReply(body);
    await msg.reply(reply);
});

client.initialize();